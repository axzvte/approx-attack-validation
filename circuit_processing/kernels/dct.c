void dct1d(int input[8], int output[8]) {
    int sums[4],diffs[4],products[4];
    for(int i=0;i<4;++i) {
        sums[i]=circuit_add(i,input[i],input[7-i]);
        diffs[i]=circuit_add(4+i,input[i],-input[7-i]);
    }
    for(int k=0;k<8;++k) {
        for(int n=0;n<4;++n) {
            int value = k%2==0 ? sums[n] : diffs[n];
            products[n]=circuit_round_shift((long long)value*q[k][n],15);
        }
        int a=circuit_add(8+3*k,products[0],products[1]);
        a=circuit_add(9+3*k,a,products[2]);
        output[k]=circuit_add(10+3*k,a,products[3]);
    }
}

void dct_kernel(int input[64], double output[64]) {
    int rows[64],coeff[64],v[8],w[8];
    double temp[64];
    for(int r=0;r<8;++r) {
        for(int c=0;c<8;++c) v[c]=input[8*r+c]-128;
        dct1d(v,w);
        for(int k=0;k<8;++k) rows[8*r+k]=w[k];
    }
    for(int c=0;c<8;++c) {
        for(int r=0;r<8;++r) v[r]=rows[8*r+c];
        dct1d(v,w);
        for(int k=0;k<8;++k) coeff[8*k+c]=w[k];
    }
    for(int r=0;r<8;++r) {
        for(int c=0;c<8;++c) {
            double s=0.0;
            for(int k=0;k<8;++k) s=s+basis[r][k]*coeff[8*k+c];
            temp[8*r+c]=s;
        }
    }
    for(int r=0;r<8;++r) {
        for(int c=0;c<8;++c) {
            double s=0.0;
            for(int k=0;k<8;++k) s=s+temp[8*r+k]*basis[c][k];
            output[8*r+c]=circuit_clip(circuit_round_even(s+128.0),0,255);
        }
    }
}
